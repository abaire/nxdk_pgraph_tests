static void GenerateCubemap(uint8_t *buffer, CubemapGeneratorMode mode) {
  static constexpr uint32_t kSliceSize = kTexturePitch * kTextureHeight;

  static constexpr uint32_t kBoxSize = 4;
  static constexpr uint32_t kAlpha = 0xFF;

  static constexpr uint32_t kColorMasks[] = {0x0000FF, 0xFF00FF, 0x00FF00, 0x00FFFF, 0xFF0000, 0xFFFF00};

  static constexpr uint32_t kCheckboxColors[6][2] = {
      {0xFF7777FF, 0xFF222222}, {0xFF553366, 0xFFDDDDDD}, {0xFF55FF55, 0xFF222222},
      {0xFF33AAAA, 0xFFDDDDDD}, {0xFFFF5555, 0xFF222222}, {0xFFAAAA33, 0xFFDDDDDD},
  };

  // +X, -X, +Y, -Y, +Z, -Z
  for (auto index = 0; index < 6; ++index) {
    switch (mode) {
      case CubemapGeneratorMode::kRadialGradient:
        GenerateSwizzledRGBRadialGradient(buffer, kTextureWidth, kTextureHeight, kColorMasks[index], kAlpha, false);
        break;
      case CubemapGeneratorMode::kCheckerboard:
        GenerateSwizzledRGBACheckerboard(buffer, 0, 0, kTextureWidth, kTextureHeight, kTexturePitch,
                                         kCheckboxColors[index][0], kCheckboxColors[index][1], kBoxSize);
        break;
      case CubemapGeneratorMode::kNoise:
        GenerateSwizzledRGBMaxContrastNoisePattern(buffer, kTextureWidth, kTextureHeight, kColorMasks[index]);
        break;
    }

    buffer += kSliceSize;
  }
}

// Fills each face of a cubemap such that every texel's color encodes its face and position.
static void GenerateCoordinateEncodedCubemap(uint8_t *buffer) {
  // Each texel encodes its face and position so that the exact texel sampled can be identified from the output:
  // R = x * 4 + 2, G = y * 4 + 2, B = face * 40 + 20 (face order +X, -X, +Y, -Y, +Z, -Z).
  // Texel (0, 0) of the +X face is instead pure magenta so that it is easily identified. R = 255 is never produced by
  // the encoding above, so this is unambiguous.
  static_assert(kTextureWidth == 64 && kTextureHeight == 64, "Texel encoding assumes a 64x64 texture");
  static constexpr uint32_t kSliceSize = kTexturePitch * kTextureHeight;
  auto linear = std::make_unique<uint32_t[]>(kTextureWidth * kTextureHeight);
  auto texture = buffer;
  for (uint32_t face = 0; face < 6; ++face) {
    auto texel = linear.get();
    for (uint32_t y = 0; y < kTextureHeight; ++y) {
      for (uint32_t x = 0; x < kTextureWidth; ++x) {
        // A8B8G8R8
        *texel++ = 0xFF000000 + ((face * 40 + 20) << 16) + ((y * 4 + 2) << 8) + (x * 4 + 2);
      }
    }
    if (!face) {
      linear[0] = 0xFFFF00FF;
    }
    swizzle_rect(reinterpret_cast<const uint8_t *>(linear.get()), kTextureWidth, kTextureHeight, texture, kTexturePitch,
                 4);
    texture += kSliceSize;
  }
}

static void GenerateMipmappedMarkerCubemap(uint8_t *buffer) {
  // Colors are ARGB. The texture format is A8B8G8R8, so red and blue are swapped when written.
  static constexpr uint32_t kPositiveXBaseColors[kMipmapCubemapLevels] = {0xFF0000A0, 0xFF00A000, 0xFFA00000,
                                                                          0xFFA0A0A0};
  static constexpr uint32_t kPositiveXMarkerColors[kMipmapCubemapLevels] = {0xFFFF00FF, 0xFF00FFFF, 0xFFFFFF00,
                                                                            0xFFFFFFFF};
  static constexpr uint32_t kRightNeighborColor = 0xFFFF8000;
  static constexpr uint32_t kBelowNeighborColor = 0xFF8000FF;
  static constexpr uint32_t kDiagonalNeighborColor = 0xFF00FF80;
  static constexpr uint32_t kLastColumnColor = 0xFF000000;
  static constexpr uint32_t kLastRowColor = 0xFF808000;
  static constexpr uint32_t kLastTexelColor = 0xFF008080;
  // -X, +Y, -Y, +Z, -Z
  static constexpr uint32_t kOtherFaceColors[5] = {0xFF603030, 0xFFFF80C0, 0xFF306030, 0xFF80C0FF, 0xFF303060};
  static constexpr uint32_t kCubemapFaceAlignment = 128;

  auto to_abgr = [](uint32_t argb) {
    return (argb & 0xFF00FF00) | ((argb & 0x00FF0000) >> 16) | ((argb & 0x000000FF) << 16);
  };

  uint32_t face_size = 0;
  for (uint32_t level = 0; level < kMipmapCubemapLevels; ++level) {
    face_size += (kTextureWidth >> level) * (kTextureHeight >> level) * 4;
  }
  face_size = (face_size + kCubemapFaceAlignment - 1) & ~(kCubemapFaceAlignment - 1);

  auto linear = std::make_unique<uint32_t[]>(kTextureWidth * kTextureHeight);
  for (uint32_t face = 0; face < 6; ++face) {
    auto texture = buffer + face * face_size;
    for (uint32_t level = 0; level < kMipmapCubemapLevels; ++level) {
      const uint32_t width = kTextureWidth >> level;
      const uint32_t height = kTextureHeight >> level;

      auto texel = linear.get();
      for (uint32_t y = 0; y < height; ++y) {
        for (uint32_t x = 0; x < width; ++x) {
          uint32_t color;
          if (face) {
            color = kOtherFaceColors[face - 1];
          } else if (x == width - 1 && y == height - 1) {
            color = kLastTexelColor;
          } else if (x == width - 1) {
            color = kLastColumnColor;
          } else if (y == height - 1) {
            color = kLastRowColor;
          } else if (x == 0 && y == 0) {
            color = kPositiveXMarkerColors[level];
          } else if (x == 1 && y == 0) {
            color = kRightNeighborColor;
          } else if (x == 0 && y == 1) {
            color = kBelowNeighborColor;
          } else if (x == 1 && y == 1) {
            color = kDiagonalNeighborColor;
          } else {
            color = kPositiveXBaseColors[level];
          }
          *texel++ = to_abgr(color);
        }
      }

      const uint32_t pitch = width * 4;
      swizzle_rect(reinterpret_cast<const uint8_t *>(linear.get()), width, height, texture, pitch, 4);
      texture += pitch * height;
    }
  }
}

